export type Locale = "he" | "en";
export type MsgKey = keyof typeof en;

const LocaleCtx = createContext<{ locale: Locale; setLocale: (l: Locale) => void; t: (k: MsgKey) => string } | null>(null);

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("he");
  useEffect(() => {
    const saved = localStorage.getItem("alphatape.locale");
    if (saved === "en" || saved === "he") setLocaleState(saved);
  }, []);
  const setLocale = (next: Locale) => {
    setLocaleState(next);
    localStorage.setItem("alphatape.locale", next);
    document.documentElement.lang = next;
    document.documentElement.dir = next === "he" ? "rtl" : "ltr";
  };
  const value = useMemo(() => ({
    locale,
    setLocale,
    t: (key: MsgKey) => (locale === "he" ? he[key] : en[key]),
  }), [locale]);
  return <LocaleCtx.Provider value={value}>{children}</LocaleCtx.Provider>;
}

export function useI18n() {
  const ctx = useContext(LocaleCtx);
  if (!ctx) throw new Error("useI18n outside provider");
  return ctx;
}
