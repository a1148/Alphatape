#!/usr/bin/env bash
# Assemble a Hugging Face Docker Space tree.
# Usage: scripts/build-hf-space.sh <target-dir>
set -euo pipefail

if [[ $# -ne 1 || -z "${1:-}" ]]; then
  echo "usage: scripts/build-hf-space.sh <target-dir>" >&2
  exit 2
fi

root=$(cd "$(dirname "$0")/.." && pwd -P)
mkdir -p "$1"
target=$(cd "$1" && pwd -P)

if [[ "$target" == "$root" || "$root" == "$target"/* ]]; then
  echo "target must be a directory outside the repository" >&2
  exit 2
fi

exclude_self=()
if [[ "$target" == "$root"/* ]]; then
  rel="${target#"$root"/}"
  exclude_self=(--exclude "/$rel/")
fi

mkdir -p "$target"
rsync -a --delete \
  --exclude '.git/' \
  --exclude 'node_modules/' \
  --exclude '.next/' \
  --exclude 'dist/' \
  --exclude 'out/' \
  --exclude '.turbo/' \
  --exclude 'coverage/' \
  --exclude '.vercel/' \
  --exclude '*.tsbuildinfo' \
  --exclude '*.log' \
  --exclude '.env' \
  --exclude '.env.local' \
  --exclude '.env.*.local' \
  --exclude 'packages/db/src/generated/' \
  "${exclude_self[@]}" \
  "$root"/ "$target"/

python3 - "$root" "$target" <<'PY'
import os
import sys

root, target = sys.argv[1], sys.argv[2]
limit = 10 * 1024 * 1024
removed = []

def binary(path):
    try:
        with open(path, "rb") as handle:
            return b"\0" in handle.read(8192)
    except OSError:
        return False

for dirpath, dirnames, filenames in os.walk(target):
    dirnames[:] = [name for name in dirnames if name != ".git"]
    for name in filenames:
        path = os.path.join(dirpath, name)
        try:
            size = os.path.getsize(path)
        except OSError:
            continue
        if size > limit and binary(path):
            os.remove(path)
            removed.append(os.path.relpath(path, target))

render_path = os.path.join(root, "Dockerfile.render")
render = open(render_path, encoding="utf-8").read()
lines = render.splitlines(keepends=True)
start = next(i for i, line in enumerate(lines) if line.startswith("FROM "))
body = "".join(lines[start:])
old_port = "ENV PORT=10000\n"
new_port = "ENV PORT=7860\nENV HOME=/home/user\nENV PGDATA=/tmp/alphatape-pg\n"
old_copy = "COPY --from=build /app /app\n"
new_copy = """# node:22-bookworm-slim already has uid 1000 (`node`). Rename it to `user`.
RUN if getent passwd 1000 >/dev/null; then \\
      name="$(getent passwd 1000 | cut -d: -f1)"; \\
      if [ "$name" != "user" ]; then usermod -l user "$name"; fi; \\
      gname="$(getent group 1000 | cut -d: -f1 || true)"; \\
      if [ -n "$gname" ] && [ "$gname" != "user" ]; then groupmod -n user "$gname"; fi; \\
      usermod -d /home/user -m user; \\
    else \\
      groupadd --gid 1000 user; \\
      useradd --create-home --home-dir /home/user --uid 1000 --gid 1000 --shell /bin/bash user; \\
    fi \\
 && mkdir -p /home/user/data /tmp/alphatape-pg \\
 && chown -R user:user /home/user /tmp/alphatape-pg
COPY --from=build --chown=user:user /app /app
RUN chown user:user /app
USER user
"""
for label, needle in (
    ("ENV PORT=10000", old_port),
    ("EXPOSE 10000", "EXPOSE 10000\n"),
    ("COPY --from=build /app /app", old_copy),
):
    if needle not in body:
        raise SystemExit(f"Dockerfile.render is missing {label}; cannot derive the Space Dockerfile")
body = body.replace(old_port, new_port, 1)
body = body.replace("EXPOSE 10000\n", "EXPOSE 7860\n", 1)
body = body.replace(old_copy, new_copy, 1)
header = """# Hugging Face Docker Space image for AlphaTape.
# Generated by scripts/build-hf-space.sh from Dockerfile.render.
# Listens on $PORT (7860). Runs as uid 1000. Embedded Postgres data stays under /tmp.
# Hardware target: CPU basic (2 vCPU, 16 GB). No persistent disk.

"""
dockerfile = header + body
if "USER user\n" not in dockerfile or "ENV PORT=7860\n" not in dockerfile or "uid 1000" not in dockerfile:
    raise SystemExit("derived Dockerfile is missing the Hugging Face user or port")
with open(os.path.join(target, "Dockerfile"), "w", encoding="utf-8") as handle:
    handle.write(dockerfile)

readme = """---
title: AlphaTape
emoji: "📈"
colorFrom: green
colorTo: gray
sdk: docker
app_port: 7860
pinned: false
suggested_hardware: cpu-basic
---

AlphaTape scans US and Tel Aviv listings. This Space runs one container on port 7860 as uid 1000 on CPU basic (2 vCPU, 16 GB). With no database URL the container starts Postgres under `/tmp`. No provider keys means labeled synthetic demo data. This is not investment advice.
"""
with open(os.path.join(target, "README.md"), "w", encoding="utf-8") as handle:
    handle.write(readme)

print(f"space tree: {target}")
if removed:
    print("excluded binary files larger than 10MB:")
    for rel in removed:
        print(f"  {rel}")
else:
    print("no binary files larger than 10MB")
PY
